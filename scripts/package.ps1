[CmdletBinding()]
param(
    [ValidateSet('Release')]
    [string]$Configuration = 'Release'
)

$ErrorActionPreference = 'Stop'
$projectRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$projectPath = Join-Path $projectRoot 'src/Inklane/Inklane.csproj'
$artifactRoot = Join-Path $projectRoot 'artifacts'
$scratchRoot = Join-Path $projectRoot '.scratch/package'
if (-not (Test-Path -LiteralPath $projectPath)) { throw 'The Inklane project was not found.' }

# Only a package that passes the regression checks and its own startup check is zipped.
$buildArtifacts = Join-Path $scratchRoot ('build-' + [guid]::NewGuid().ToString('N'))
& (Join-Path $PSScriptRoot 'build.ps1') -Configuration $Configuration -ArtifactsPath $buildArtifacts

Push-Location $projectRoot
try {
    $version = (& dotnet msbuild $projectPath -getProperty:Version).Trim()
    if ($LASTEXITCODE -ne 0 -or $version -notmatch '^\d+\.\d+\.\d+(?:-[a-zA-Z0-9.]+)?$') {
        throw "Could not determine a safe package version: $version"
    }
}
finally {
    Pop-Location
}
$packageName = "Inklane-$version-win-x64"
$packagePath = [System.IO.Path]::GetFullPath((Join-Path $artifactRoot $packageName))
$allowedPrefix = [System.IO.Path]::GetFullPath($artifactRoot).TrimEnd('\') + '\'
if (-not $packagePath.StartsWith($allowedPrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw 'The output path is outside artifacts/.'
}
$markerPath = Join-Path $packagePath '.inklane-package'
if (Test-Path -LiteralPath $packagePath) {
    if (-not (Test-Path -LiteralPath $markerPath)) {
        throw "Refusing to replace an unrecognized directory: $packagePath"
    }
    Remove-Item -LiteralPath $packagePath -Recurse -Force
}
New-Item -ItemType Directory -Path $packagePath, $scratchRoot -Force | Out-Null
Set-Content -LiteralPath $markerPath -Value 'Generated by scripts/package.ps1. Safe to replace when rebuilding.' -Encoding utf8

Push-Location $projectRoot
try {
    & dotnet publish $projectPath --artifacts-path $buildArtifacts --configuration $Configuration --runtime win-x64 --self-contained true --output $packagePath -p:PublishSingleFile=false -p:PublishTrimmed=false -p:DebugType=None -p:DebugSymbols=false -p:RestoreLockedMode=true
    if ($LASTEXITCODE -ne 0) { throw 'Self-contained publish failed.' }
    foreach ($document in @('README.md', 'THIRD-PARTY-NOTICES.md')) {
        $documentPath = Join-Path $projectRoot $document
        if (-not (Test-Path -LiteralPath $documentPath)) { throw "Missing distribution document: $document" }
        Copy-Item -LiteralPath $documentPath -Destination $packagePath
    }
    # Preserve the documentation links in README.md in the portable distribution.
    Copy-Item -LiteralPath (Join-Path $projectRoot 'docs') -Destination $packagePath -Recurse
    $runtimeNoticeRoot = Split-Path -Parent (Get-Command dotnet).Source
    $licensePath = Join-Path $packagePath 'licenses'
    New-Item -ItemType Directory -Path $licensePath -Force | Out-Null
    foreach ($notice in @('LICENSE.txt', 'ThirdPartyNotices.txt')) {
        $noticePath = Join-Path $runtimeNoticeRoot $notice
        if (-not (Test-Path -LiteralPath $noticePath)) { throw "Missing .NET runtime notice: $noticePath" }
        Copy-Item -LiteralPath $noticePath -Destination (Join-Path $licensePath ('dotnet-' + $notice))
    }

    $exePath = Join-Path $packagePath 'Inklane.exe'
    if (-not (Test-Path -LiteralPath $exePath)) { throw 'Publish did not produce Inklane.exe.' }
    $smokePath = Join-Path $scratchRoot ("startup-" + [guid]::NewGuid().ToString('N') + '.json')
    # Launch from a directory outside the app/source tree to catch relative-resource assumptions.
    $process = Start-Process -FilePath $exePath -ArgumentList @('--smoke-test', ('"' + $smokePath + '"')) -WorkingDirectory $scratchRoot -WindowStyle Hidden -PassThru
    if (-not $process.WaitForExit(30000)) {
        $process.Kill()
        throw 'Packaged startup did not finish within 30 seconds.'
    }
    $process.Refresh()
    if ($process.ExitCode -ne 0 -or -not (Test-Path -LiteralPath $smokePath)) {
        throw "Packaged startup failed (exit code $($process.ExitCode))."
    }
    $smokeResult = Get-Content -LiteralPath $smokePath -Raw | ConvertFrom-Json
    if ($smokeResult.success -ne $true) { throw 'Packaged startup did not report success.' }
    if (-not $smokeResult.runtimeDirectory) { throw 'Startup check did not identify the loaded runtime.' }
    $loadedRuntimePath = [System.IO.Path]::GetFullPath([string]$smokeResult.runtimeDirectory).TrimEnd('\')
    if (-not $loadedRuntimePath.Equals($packagePath.TrimEnd('\'), [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Startup used a runtime outside the package: $loadedRuntimePath"
    }
    $zipPath = Join-Path $artifactRoot ($packageName + '.zip')
    Compress-Archive -LiteralPath $packagePath -DestinationPath $zipPath -Force
    $checksum = (Get-FileHash -LiteralPath $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    Set-Content -LiteralPath ($zipPath + '.sha256') -Value ($checksum + '  ' + [System.IO.Path]::GetFileName($zipPath)) -Encoding ascii
    Write-Host "Packaged and startup-checked: $exePath"
    Write-Host "Archive: $zipPath"
    Write-Host "SHA-256: $checksum"
}
finally {
    Pop-Location
}
